public class Patient {
    private int patientId;
    private String name;
    private int age;
    private String disease;


    public int getPatientId() {
        return patientId;
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }

    public String getDisease() {
        return disease;
    }
}
